/* A cyber-security monitoring system creates a compact fingerprint for every message transmitted across its
internal network. The fingerprint is generated by dividing each word into overlapping character pairs rather
than pairing characters from opposite ends. The transformation helps produce a deterministic code from
the message while retaining information about the sequence of characters.
For each word, calculate the absolute difference between the alphabet positions of every pair of
consecutive characters. For each difference, append the difference if it is nonzero; otherwise, append the
sum of the two alphabet positions. If a word contains only one character, append its alphabet position.
Concatenate the codes of all words to obtain the message fingerprint.
Input Format
A single line containing the message S.
Output Format
Print the fingerprint as a string.
Constraints
 1 <= |S| <= 200
 Only English letters and single spaces are allowed.
 Character positions are case-insensitive.
 Process overlapping pairs from leŌ to right.
 A single-character word produces its alphabet position.
Example
Input:
CAB
Output:
21
*/

import javax.xml.namespace.QName;
import java.util.Scanner;
class  CybersecurityMessageFingerprint{
    public static void main(String[] args){
        Scanner sc =new Scanner(System.in);

        System.out.print("Enter the message : ");
        String message = sc.nextLine().toUpperCase();
        String result = "";

        int start = 0;
        for(int i = 0 ; i<=message.length() ; i++){
            if(i == message.length() || message.charAt(i) == ' '){
                int left = start;
                int right = start + 1;

                while(right<i){
                    int a = message.charAt(left) - 'A' + 1;
                    int b = message.charAt(right)- 'A' + 1;

                    int diff = a-b;
                    int sum = a+b;

                    if(diff>0){
                        result = result + diff;
                    }
                    else if(diff == 0){
                        result = result + sum ;
                    }
                    else{
                        diff = -diff;
                        result = result + diff;
                    }
                    left++;
                    right++;
                }
                if(left==right || message.length()==1){
                    int mid = message.charAt(left) - 'A' + 1;
                    result = result + mid ;
                }
                start = i+1;
            }
        }
        System.out.println(result);
        sc.close();
    }
}